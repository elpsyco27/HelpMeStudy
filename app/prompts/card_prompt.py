def build_card_prompt(note_markdown: str) -> str:
    return f"""你是一个学习复习卡片生成助手。

请根据下面的 Markdown 学习笔记，生成 Markdown 表格形式的复习卡片。

表格列必须严格为：

| 问题 | 答案 | 易错点 | 来源 |
| --- | --- | --- | --- |

要求：
- 只输出 Markdown 表格，不要输出解释性前言。
- 每张卡片的问题要清晰、具体，适合自测。
- 答案要准确、简洁。
- 易错点要指出容易混淆或遗漏的地方。
- 来源必须保留笔记中的页码信息，例如“第 3 页”或“第 3, 4 页”。
- 不要编造笔记中没有的内容。
- 尽量覆盖以下 5 类卡片：
  1. 概念定义卡
  2. 区分辨析卡
  3. 公式理解卡
  4. 应用场景卡
  5. 易错点卡

Markdown 学习笔记：
\"\"\"
{note_markdown}
\"\"\"
"""
